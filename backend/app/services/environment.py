"""EnvironmentalDataProvider: pluggable sources of environmental predictors.

MVP providers
- DemoEnvironmentalProvider  → SYNTHETIC smooth fields (labelled DEMO). For trying the pipeline only.
- WorldClimProvider          → REAL WorldClim v2.1 bioclim + elevation GeoTIFFs read locally with rasterio.
                               Download with `python scripts/download_worldclim.py --res 10m`.
                               Fick & Hijmans (2017) Int. J. Climatol. 37:4302–4315. https://www.worldclim.org

Prepared (interface only; raise NotConfigured until implemented)
- CHELSAProvider (https://chelsa-climate.org), CopernicusLandCoverProvider (CGLS-LC100 / ESA WorldCover),
  NASASRTMProvider (SRTM/NASADEM elevation), distance-to-water from OSM/HydroSHEDS.
"""
from __future__ import annotations

import os
from abc import ABC, abstractmethod
from dataclasses import dataclass

import numpy as np

from ..config import get_settings
from .geo import Grid


class NotConfigured(Exception):
    pass


@dataclass
class Variable:
    code: str
    name: str
    units: str
    source: str


class EnvironmentalDataProvider(ABC):
    code: str
    label: str
    is_demo: bool = False
    native_res_deg: float = 0.1667
    citation: str = ""

    @abstractmethod
    def variables(self) -> list[Variable]: ...

    @abstractmethod
    def grid(self, grid: Grid, variables: list[str] | None = None) -> dict[str, np.ndarray]:
        """Return {var: array(height, width)} sampled at the grid cell centres (NaN = no data)."""

    def available(self) -> tuple[bool, str]:
        return True, "ok"

    def describe(self) -> dict:
        ok, msg = self.available()
        return {
            "code": self.code, "label": self.label, "is_demo": self.is_demo, "available": ok, "status": msg,
            "native_resolution_deg": self.native_res_deg, "citation": self.citation,
            "variables": [v.__dict__ for v in self.variables()],
        }


def _slope_deg(elev: np.ndarray, grid: Grid) -> np.ndarray:
    if min(elev.shape) < 2:
        return np.full(elev.shape, np.nan)
    lat = np.deg2rad(grid.centers()[1])
    dy = grid.res * 111_320.0
    dx = grid.res * 111_320.0 * np.cos(lat)
    gy, gx = np.gradient(elev)
    return np.degrees(np.arctan(np.hypot(gx / dx, gy / dy)))


class DemoEnvironmentalProvider(EnvironmentalDataProvider):
    """Deterministic synthetic landscape. NOT real data — every output derived from it is DEMO."""

    code = "demo"
    label = "DEMO synthetic environment (not real data)"
    is_demo = True
    native_res_deg = 0.02
    citation = "Synthetic fields generated by BIOQUEST for demonstration. Not real environmental data."

    def variables(self):
        return [
            Variable("elev", "Elevation (synthetic)", "m", "DEMO"),
            Variable("bio1", "Annual mean temperature (synthetic)", "°C", "DEMO"),
            Variable("bio12", "Annual precipitation (synthetic)", "mm", "DEMO"),
            Variable("bio4", "Temperature seasonality (synthetic)", "sd×100", "DEMO"),
            Variable("slope", "Slope (derived from synthetic elevation)", "°", "DEMO"),
        ]

    def grid(self, grid: Grid, variables=None):
        LON, LAT = grid.centers()
        elev = (
            3000
            + 1300 * np.sin(LAT * 4.1) * np.cos(LON * 3.3)
            + 700 * np.sin(LAT * 13.0 + LON * 9.0)
            + 120 * np.cos(LAT * 31.0 - LON * 23.0)
        )
        elev = np.clip(elev, 50, 5600)
        bio1 = 27.0 - 0.0058 * elev + 1.2 * np.sin(LON * 7.0)
        bio12 = np.clip(650 + 450 * np.sin(LON * 5.0 + 1.0) + 300 * np.cos(LAT * 9.0) - 0.05 * (elev - 3000), 50, None)
        bio4 = 120 + 60 * np.abs(np.sin(LAT * 2.0)) + 0.01 * elev
        out = {"elev": elev, "bio1": bio1, "bio12": bio12, "bio4": bio4, "slope": _slope_deg(elev, grid)}
        return {k: v for k, v in out.items() if not variables or k in variables}


class WorldClimProvider(EnvironmentalDataProvider):
    code = "worldclim"
    label = "WorldClim v2.1 (local GeoTIFFs)"
    citation = ("Fick, S.E. & Hijmans, R.J. (2017) WorldClim 2: new 1-km spatial resolution climate surfaces "
                "for global land areas. Int. J. Climatol. 37: 4302–4315.")
    VARS = {
        "bio1": ("Annual mean temperature", "°C"),
        "bio4": ("Temperature seasonality", "sd×100"),
        "bio12": ("Annual precipitation", "mm"),
        "bio15": ("Precipitation seasonality", "CV"),
        "elev": ("Elevation", "m"),
        "slope": ("Slope (derived from WorldClim elevation)", "°"),
    }

    def __init__(self, directory: str | None = None):
        self.dir = directory or get_settings().worldclim_dir

    def _path(self, var: str) -> str | None:
        if not os.path.isdir(self.dir):
            return None
        suffix = "elev" if var == "elev" else f"bio_{var[3:]}"
        for f in os.listdir(self.dir):
            if f.startswith("wc2.1_") and f.endswith(f"_{suffix}.tif"):
                return os.path.join(self.dir, f)
        return None

    def available(self):
        try:
            import rasterio  # noqa: F401
        except ImportError:
            return False, "rasterio not installed"
        missing = [v for v in self.VARS if v != "slope" and not self._path(v)]
        if missing:
            return False, f"missing GeoTIFFs for {missing} in {self.dir} (run scripts/download_worldclim.py)"
        return True, "ok"

    @property
    def native_res_deg(self):  # type: ignore[override]
        p = self._path("bio1")
        if not p:
            return 0.1667
        import rasterio
        with rasterio.open(p) as src:
            return abs(src.transform.a)

    def variables(self):
        return [Variable(k, n, u, "WorldClim v2.1") for k, (n, u) in self.VARS.items()]

    def _sample(self, path: str, grid: Grid) -> np.ndarray:
        import rasterio
        from rasterio.windows import from_bounds

        LON, LAT = grid.centers()
        with rasterio.open(path) as src:
            pad = grid.res
            win = from_bounds(grid.minlon - pad, grid.minlat - pad, grid.maxlon + pad, grid.maxlat + pad,
                              src.transform).round_offsets().round_lengths()
            arr = src.read(1, window=win, boundless=True, fill_value=np.nan, masked=False).astype("float32")
            nod = src.nodata
            t = src.window_transform(win)
        if nod is not None:
            arr[arr == nod] = np.nan
        arr[arr < -1e30] = np.nan
        col = np.floor((LON - t.c) / t.a).astype(int)
        row = np.floor((LAT - t.f) / t.e).astype(int)
        ok = (row >= 0) & (row < arr.shape[0]) & (col >= 0) & (col < arr.shape[1])
        out = np.full(LON.shape, np.nan, dtype="float32")
        out[ok] = arr[row[ok], col[ok]]
        return out

    def grid(self, grid: Grid, variables=None):
        ok, msg = self.available()
        if not ok:
            raise NotConfigured(msg)
        want = variables or list(self.VARS)
        out = {}
        for v in want:
            if v == "slope":
                continue
            out[v] = self._sample(self._path(v), grid)
        if "slope" in want:
            elev = out.get("elev")
            if elev is None:
                elev = self._sample(self._path("elev"), grid)
            out["slope"] = _slope_deg(elev, grid)
        return out


class _Planned(EnvironmentalDataProvider):
    def variables(self):
        return []

    def available(self):
        return False, "planned adapter – not implemented in the MVP"

    def grid(self, grid, variables=None):
        raise NotConfigured(f"{self.label}: not implemented yet")


class CHELSAProvider(_Planned):
    code, label = "chelsa", "CHELSA climatologies (planned)"


class CopernicusLandCoverProvider(_Planned):
    code, label = "copernicus_lc", "Copernicus / ESA WorldCover land cover (planned)"


class NASASRTMProvider(_Planned):
    code, label = "nasadem", "NASA SRTM / NASADEM elevation (planned)"


PROVIDERS: dict[str, EnvironmentalDataProvider] = {
    p.code: p for p in [DemoEnvironmentalProvider(), WorldClimProvider(), CHELSAProvider(),
                        CopernicusLandCoverProvider(), NASASRTMProvider()]
}


def get_provider(code: str | None = None) -> EnvironmentalDataProvider:
    code = code or get_settings().env_provider
    if code not in PROVIDERS:
        raise NotConfigured(f"unknown environmental provider '{code}'")
    return PROVIDERS[code]
